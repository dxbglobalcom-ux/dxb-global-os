#!/usr/bin/env node
// gen-study-card-stubs.mjs — fills every non-EXCLUDED INTEGRATION-TRACKER row
// whose Study Card file does not exist yet with a template STUB card.
// Idempotent: never overwrites an existing card (full or stub).
// CLI: node scripts/gen-study-card-stubs.mjs
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import path from "node:path";

const TRACKER = ".planning/research/INTEGRATION-TRACKER.md";
const BASE = ".planning/research";

const text = readFileSync(TRACKER, "utf8");
const main = text.split("## Excluded Items")[0];
const rows = main
  .split("\n")
  .filter((l) => /^\|/.test(l) && !/^\|\s*-+/.test(l))
  .map((l) => l.split("|").map((s) => s.trim()))
  .filter((c) => c[3] && c[3] !== "Status");

function stubFor(c) {
  const [, item, category, status, phase, owner, trigger, card] = c;
  const slug = path.basename(card, ".md");
  const tbd = `TBD — filled at Phase ${phase} study step`;
  return `# Study Card: ${item} (STUB)

> STUB generated by scripts/gen-study-card-stubs.mjs from the tracker row.
> Full study happens at the START of the phase that uses this tool (INTEG-01).

- **Tool:** ${item}
- **Slug:** ${slug}
- **Category:** ${category}
- **Status:** ${status}
- **Target Phase:** ${phase}
- **Owner (dept/tier):** ${owner}
- **Trigger Type:** ${trigger}
- **Source:** ${tbd}
- **Pinned Version:** ${tbd}
- **Purpose:** ${tbd}
- **Official Docs URL:** ${tbd}
- **Key API / Usage Notes:** ${tbd}
- **Known Pitfalls:** ${tbd}
- **Install Command:** ${tbd} (recorded before install; never run blind)
- **Legitimacy Verdict:** ${tbd}

## Lifecycle Checklist
- [ ] STUDY
- [ ] INSTALL
- [ ] ADOPT
- [ ] EMBED
`;
}

let created = 0;
let skipped = 0;
for (const c of rows) {
  const status = c[3];
  const card = c[7];
  if (status === "EXCLUDED" || !card || card === "-") continue;
  const file = path.join(BASE, card);
  if (existsSync(file)) {
    skipped++;
    continue;
  }
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, stubFor(c));
  created++;
}
console.log(`stub generator: ${created} created, ${skipped} already existed`);
